test('support bundle validates exact byte length, digest, filename, MIME, size and gzip before download', async () => {
  const good = bundle(); assert.equal((await decodeComponentsSupport(good, webcrypto)).length, good.bytes);
  const variants = [ { filename: '../example.rivetin-support.json.gz' }, { filename: 'example.html' }, { contentType: 'text/html' }, { bytes: 1024 * 1024 + 1 }, { bytes: good.bytes + 1 }, { sha256: 'a'.repeat(64) }, { sha256: 'A'.repeat(64) }, { data: 'not base64!' }, { data: Buffer.from('not gzip').toString('base64'), bytes: 8 } ];
  for (const patch of variants) await assert.rejects(decodeComponentsSupport({ ...good, ...patch }, webcrypto), /SUPPORT_BUNDLE_INVALID/);
});

test('support download only GETs local API, uses Blob and releases object URL; failure does not download', async t => {
  const good = bundle(); let invalid = false, clicked = 0, revoked = 0;
  const view = await mount(t, route => route === '/components/support' ? invalid ? { ...good, sha256: '0'.repeat(64) } : good : fixture());
  view.dom.window.URL.createObjectURL = blob => { assert.equal(blob.type, 'application/gzip'); return 'blob:example'; };
  view.dom.window.URL.revokeObjectURL = url => { assert.equal(url, 'blob:example'); revoked++; };
  view.dom.window.HTMLAnchorElement.prototype.click = function () { assert.equal(this.download, good.filename); clicked++; };
  await view.click('.rv-components-support'); await new Promise(resolve => setTimeout(resolve, 10));
  assert.equal(clicked, 1); assert.equal(revoked, 1); assert.match(view.root.textContent, /支持包已下载/);
  invalid = true; await view.click('.rv-components-support'); assert.equal(clicked, 1); assert.match(view.root.textContent, /SUPPORT_BUNDLE_INVALID/);
  assert.equal(view.calls.some(row => row[1] === 'POST'), false); assert.ok(view.calls.every(row => row[0].startsWith('/components/')));
});

