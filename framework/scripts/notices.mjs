import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(path.join(root, 'package.json')), seen = new Map();
async function visit(name) {
  if (seen.has(name)) return;
  const file = require.resolve(`${name}/package.json`), pkg = JSON.parse(await readFile(file, 'utf8'));
  let license;
  for (const candidate of ['LICENSE', 'license', 'LICENSE.txt', 'LICENSE-MIT']) {
    try { license = await readFile(path.join(path.dirname(file), candidate), 'utf8'); break; } catch (error) { if (error.code !== 'ENOENT') throw error; }
  }
  if (!license) throw new Error(`License missing: ${name}`);
  const licenseId = typeof pkg.license === 'string' ? pkg.license : pkg.license?.type || pkg.licenses?.map(item => item.type).filter(Boolean).join(' AND ');
  if (!licenseId) throw new Error(`License identifier missing: ${name}`);
  seen.set(name, { name, version: pkg.version, license: licenseId, text: license.trim() });
  for (const dependency of Object.keys(pkg.dependencies || {})) await visit(dependency);
}
for (const name of Object.keys(JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8')).dependencies)) await visit(name);
const components = [...seen.values()].sort((a, b) => a.name.localeCompare(b.name));
components.push({ name: 'GitHub Octicons (mark-github)', version: '9a274e212ee25c400ff666ce25a57866b7eacc25', license: 'MIT', text: (await readFile(path.join(root, 'vendor/octicons/LICENSE'), 'utf8')).trim() });
const data = { projectLicense: (await readFile(path.join(root, '../LICENSE'), 'utf8')).trim(), components };
await writeFile(path.join(root, 'src/notices.js'), '// Generated by scripts/notices.mjs.\nexport default ' + JSON.stringify(data, null, 2) + ';\n');
await writeFile(path.join(root, 'THIRD_PARTY_NOTICES.txt'), components.map(item => `${item.name} ${item.version} (${item.license})\n\n${item.text}\n`).join('\n---\n\n'));
console.log(`Generated ${components.length} runtime dependency notices from installed locked packages.`);
