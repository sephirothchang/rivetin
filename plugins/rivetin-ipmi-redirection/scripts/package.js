import { execFileSync } from 'node:child_process';
import { mkdir, readFile, copyFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { hash, validatePackage } from '../../../framework/server/manifest.js';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const manifest = JSON.parse(await readFile(path.join(root, 'sea-map.json')));
const pkg = JSON.parse(await readFile(path.join(root, 'package.json')));
if (!/^rivetin-[a-z0-9]+(?:-[a-z0-9]+)*$/.test(pkg.name) || manifest.name !== pkg.name || manifest.metadata.version !== pkg.version) throw new Error('Plugin identity/version mismatch');
await readFile(path.join(root, 'dist/production/build/remoteEntry.js'));
await copyFile(path.join(root, 'LICENSE'), path.join(root, 'dist/production/build/LICENSE'));
const stage = path.join(root, '.packaging', manifest.metadata.version), output = path.join(root, 'release');
await mkdir(stage, { recursive: true }); await mkdir(output, { recursive: true });
await copyFile(path.join(root, 'sea-map.json'), path.join(stage, 'sea-map.json'));
execFileSync('tar', ['-czf', path.join(stage, 'build.tar.gz'), '-C', path.join(root, 'dist/production'), 'build']);
const artifact = path.join(output, `${pkg.name}-${manifest.metadata.version}.tar.gz`);
execFileSync('tar', ['-czf', artifact, '-C', stage, 'sea-map.json', 'build.tar.gz']);
const listing = execFileSync('tar', ['-tzf', artifact], { encoding: 'utf8' }).trim().split(/\r?\n/);
if (listing.length !== 2 || !listing.includes('sea-map.json') || !listing.includes('build.tar.gz')) throw new Error('Unexpected package structure');
console.log(`Local artifact only: ${artifact}`);
console.log('No upload or Tower connection is implemented by this script.');
const descriptor = JSON.parse(await readFile(path.join(root, 'rivetin.json'), 'utf8'));
const files = [];
for (const [file, source] of [['web/plugin.js', 'dist/rivetin/plugin.js'], ['LICENSE', 'LICENSE']]) {
  const content = await readFile(path.join(root, source));
  files.push({ path: file, sha256: hash(content), data: content.toString('base64') });
}
const bundle = Buffer.from(JSON.stringify({ format: 'rivetin-package-v1', manifest: descriptor, files }));
validatePackage(bundle);
await (await import('node:fs/promises')).writeFile(path.join(output, `${pkg.name}-${pkg.version}.rivetin.json`), bundle);
console.log('Rivetin child package built (upload does not execute code).');
